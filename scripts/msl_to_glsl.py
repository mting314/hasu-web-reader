#!/usr/bin/env python3
"""Convert the game's toon shader (Metal source from its asset bundles) to GLSL for three.js.

The iOS bundles keep Unity's shaders as Metal source generated by HLSLcc. These programs are
straight-line code over a few uniform blocks, so a mechanical translation is exact:
  Metal types -> GLSL (half -> float, float3 -> vec3, ...), fma -> a*b+c, rsqrt -> inversesqrt,
  dfdx -> dFdx, `tex.sample(s, uv)` -> texture(tex, uv), vector comparisons -> lessThan() etc.,
  uniform-block fields -> uniforms, stage inputs/outputs -> varyings / gl_Position / gl_FragColor.
The converted body is left as it is; only its inputs are adapted to three.js:
  - Vertex inputs come from three's skinning/morph chunks, moved into Unity's "object space" of a
    skinned mesh, which is its root bone (uObjectToWorld / uWorldToObject, set per draw).
  - Unity's UV origin is bottom-left, glTF's top-left: the vertex stage hands the body Unity UVs
    (v flipped back) and every texture fetch flips v again (U2G), so tiling/offset and the
    computed matcap UVs work exactly as in Unity.
  - unity_MatrixVP = projectionMatrix * viewMatrix, unity_MatrixV = viewMatrix,
    _WorldSpaceCameraPos = cameraPosition.
What three.js has no equivalent for is stubbed explicitly: real-time shadow-map lookups return
"lit" (the reader has no shadow maps; with _MainLightShadowParams.x = 0 the game's own formula
gives the same), the shadow matrices become the identity and the additional-light arrays shrink
to one entry (the loop over them runs zero times, _AdditionalLightsCount = 0).

Input: the programs extracted from __ubertoonshader.shader. Every compiled variant in the bundle
has _ALPHATEST_ON; the _USEENVIRONMENTMAPTEX_ON variants (vertex 2/7, fragment 5/15) are
byte-identical to the ones below, so these four programs cover every UberToon material. The eye
shader and the two older shaders a few NPC costumes use (see PROGRAMS) are extracted the same
way, with the decompiled ShaderLab text of each shader beside the variants dir.
Output: src/engine/shaders/uberToonGame.ts, complete vertex/fragment sources per pass plus the
uniforms each one reads.

Usage: uv run scripts/msl_to_glsl.py <variants dir> [--out src/engine/shaders/uberToonGame.ts]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROGRAMS = {
    # name in the output -> (file, stage)
    "FORWARD_VERT": ("uber_pass1_ForwardLit_progVertex_6.metal", "vertex"),
    "FORWARD_FRAG": ("uber_pass1_ForwardLit_progFragment_14.metal", "fragment"),
    "OUTLINE_VERT": ("uber_pass0_Outline_progVertex_1.metal", "vertex"),
    "OUTLINE_FRAG": ("uber_pass0_Outline_progFragment_4.metal", "fragment"),
    "EYE_VERT": ("eye_pass0_Forward_progVertex_0.metal", "vertex"),
    "EYE_FRAG": ("eye_pass0_Forward_progFragment_1.metal", "fragment"),
    # The older shaders some NPC costumes use (Sachi's face and eyes): MELPOT/Toon/
    # UberToonShader(HLSLMacros) has UberToonShader's passes and variant layout (Outline 1/4,
    # ForwardLit 6/14, the _USEENVIRONMENTMAPTEX_ON ones byte-identical) but its own property set
    # (a tertiary colour layer, no wetness/UV maps); MELPOT/Toon/UberToonShader_Eye has one
    # Forward variant (_HIGHLIGHTBLENDMODE_ADDITIVE), used for every material of that shader.
    "HLSL_FORWARD_VERT": ("hlsl_pass1_ForwardLit_progVertex_6.metal", "vertex"),
    "HLSL_FORWARD_FRAG": ("hlsl_pass1_ForwardLit_progFragment_14.metal", "fragment"),
    "HLSL_OUTLINE_VERT": ("hlsl_pass0_Outline_progVertex_1.metal", "vertex"),
    "HLSL_OUTLINE_FRAG": ("hlsl_pass0_Outline_progFragment_4.metal", "fragment"),
    "UBER_EYE_VERT": ("ueye_pass0_Forward_progVertex_1.metal", "vertex"),
    "UBER_EYE_FRAG": ("ueye_pass0_Forward_progFragment_3.metal", "fragment"),
}
# shader -> its decompiled ShaderLab text beside the variants dir (for the property defaults)
SHADER_TEXTS = {
    "UBER_DEFAULTS": "MELPOT__Toon__UberToonShader.shader.txt",
    "EYE_DEFAULTS": "Character__ToonShader_CharacterEye.shader.txt",
    "HLSL_DEFAULTS": "MELPOT__Toon__UberToonShader(HLSLMacros).shader.txt",
    "UBER_EYE_DEFAULTS": "MELPOT__Toon__UberToonShader_Eye.shader.txt",
}

TYPE_MAP = {
    "half4": "vec4", "half3": "vec3", "half2": "vec2", "half": "float",
    "float4": "vec4", "float3": "vec3", "float2": "vec2",
    "int4": "ivec4", "int3": "ivec3", "int2": "ivec2",
    "uint4": "uvec4", "uint3": "uvec3", "uint2": "uvec2",
    "bool4": "bvec4", "bool3": "bvec3", "bool2": "bvec2",
    "float4x4": "mat4", "float3x3": "mat3",
}

# Unity matrices (HLSLcc arrays of columns; GLSL mat4[k] is also column k) -> GLSL expressions
MATRICES = {
    "unity_ObjectToWorld": "uObjectToWorld",
    "unity_WorldToObject": "uWorldToObject",
    "unity_MatrixVP": "uMatrixVP",
    "unity_MatrixV": "viewMatrix",
    "_MainLightWorldToShadow": "uIdentity",
    "_AdditionalLightsWorldToShadow": "uIdentity",
}

# globals three.js provides itself (or that the wrapper defines)
PROVIDED = {"_WorldSpaceCameraPos"}

COMPARE_FUNCS = {"<": "lessThan", "<=": "lessThanEqual", ">": "greaterThan", ">=": "greaterThanEqual",
                 "==": "equal", "!=": "notEqual"}

VERTEX_PRELUDE = """\
#include <common>
#include <skinning_pars_vertex>
#include <morphtarget_pars_vertex>
attribute vec4 tangent;
uniform mat4 uObjectToWorld;
uniform mat4 uWorldToObject;
#define fma_(a, b, c) ((a) * (b) + (c))
vec2 U2G(vec2 uv) { return vec2(uv.x, 1.0 - uv.y); }
"""

VERTEX_INPUTS = """\
  #include <skinbase_vertex>
  #include <beginnormal_vertex>
  #include <morphnormal_vertex>
  #include <skinnormal_vertex>
  vec3 skinnedTangent = tangent.xyz;
  #ifdef USE_SKINNING
  skinnedTangent = (skinMatrix * vec4(skinnedTangent, 0.0)).xyz;
  #endif
  #include <begin_vertex>
  #include <morphtarget_vertex>
  #include <skinning_vertex>
  // Unity's object space for a skinned mesh is its root bone's
  mat4 meshToObject = uWorldToObject * modelMatrix;
  vec4 in_POSITION0 = vec4((meshToObject * vec4(transformed, 1.0)).xyz, 1.0);
  vec3 in_NORMAL0 = normalize(mat3(meshToObject) * objectNormal);
  vec4 in_TANGENT0 = vec4(normalize(mat3(meshToObject) * skinnedTangent), tangent.w);
  vec4 in_TEXCOORD0 = vec4(U2G(uv), 0.0, 0.0);
  vec4 in_TEXCOORD1 = vec4(0.0);
  mat4 uMatrixVP = projectionMatrix * viewMatrix;
  const mat4 uIdentity = mat4(1.0);
"""

FRAGMENT_PRELUDE = """\
uniform mat4 uObjectToWorld;
uniform mat4 uWorldToObject;
#define fma_(a, b, c) ((a) * (b) + (c))
#define _WorldSpaceCameraPos cameraPosition
const mat4 uIdentity = mat4(1.0);
vec2 U2G(vec2 uv) { return vec2(uv.x, 1.0 - uv.y); }
"""


def parse_structs(src: str) -> dict[str, list[tuple[str, str, int | None]]]:
    structs = {}
    for name, body in re.findall(r"struct (\w+)\s*\{(.*?)\};", src, re.S):
        fields = []
        for line in body.split(";"):
            line = line.strip()
            m = re.match(r"(\w+)\s+(\w+)(?:\[(\d+)\])?(?:\s*\[\[.*\]\])?$", line)
            if m:
                fields.append((m.group(1), m.group(2), int(m.group(3)) if m.group(3) else None))
        structs[name] = fields
    return structs


def split_top(expr: str, ops: list[str]) -> tuple[str, str, str] | None:
    """Split `expr` at its first top-level comparison operator."""
    depth = 0
    i = 0
    while i < len(expr):
        ch = expr[i]
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif depth == 0:
            for op in sorted(ops, key=len, reverse=True):
                if expr.startswith(op, i):
                    return expr[:i], op, expr[i + len(op):]
        i += 1
    return None


def vector_compares(s: str) -> str:
    """`bvecN.xy = (a != b);` is component-wise in Metal; GLSL needs notEqual(a, b)."""
    def fix(m):
        lhs, swz, inner = m.group(1), m.group(2), m.group(3)
        if len(swz) < 2:
            return m.group(0)
        parts = split_top(inner, list(COMPARE_FUNCS))
        if parts is None:
            return m.group(0)
        a, op, b = parts
        return f"{lhs}.{swz} = {COMPARE_FUNCS[op]}({a.strip()}, {b.strip()});"
    return re.sub(r"^(\s*u_xlatb\d+)\.([xyzw]+)\s*=\s*\((.*)\);\s*$", fix, s, flags=re.M)


INLINE_SAMPLER = re.compile(r"^\s*constexpr sampler (\w+)\(([^)]*)\);\s*$\n?", re.M)


def inline_samplers(body: str) -> dict[str, dict[str, str]]:
    """Unity inline sampler states (`sampler_Linear_Repeat`), which HLSLcc declares in the body as
    `constexpr sampler name(filter::linear, mip_filter::nearest, address::repeat)`. They override
    the texture's own filtering and wrapping; GLSL has no inline samplers, so the state goes to the
    material instead: texture uniform -> {filter, mip_filter, address}."""
    states = {name: dict(a.strip().split("::") for a in args.split(",")) for name, args in INLINE_SAMPLER.findall(body)}
    out = {}
    for name, state in states.items():
        for tex in re.findall(rf"(\w+)\.sample\(\s*{name}\s*,", body):
            out[tex] = state
    return out


def convert_body(body: str, stage: str) -> str:
    s = INLINE_SAMPLER.sub("", body)
    for mt, gt in sorted(TYPE_MAP.items(), key=lambda kv: -len(kv[0])):
        s = re.sub(rf"\b{mt}\b", gt, s)
    # half / float literal suffixes: 0.0h, 1.0f
    s = re.sub(r"\b(\d+\.\d*(?:e[-+]?\d+)?)[hf]\b", r"\1", s)
    # uniform-block member access -> plain names
    s = re.sub(r"\b(?:FGlobals|VGlobals|UnityPerDraw|UnityPerMaterial|AdditionalLights|LightShadows)\.", "", s)

    def mat(m):
        name, idx = m.group(1), m.group(2)
        target = MATRICES.get(name)
        if target is None:
            raise ValueError(f"unknown matrix {name}")
        return f"{target}[({idx}) & 3]" if target == "uIdentity" else f"{target}[{idx}]"
    s = re.sub(r"hlslcc_mtx4x4(\w+)\[([^\]]+)\]", mat, s)
    # texture sampling (Unity UVs -> glTF UVs at every fetch)
    s = re.sub(r"(\w+)\.sample_compare\([^;]*\)", "1.0", s)  # shadow maps: always lit
    s = re.sub(r"(\w+)\.sample\(\s*\w+\s*,\s*([^;]*?),\s*level\(([^)]*)\)\s*\)", r"textureLod(\1, U2G(\2), \3)", s)
    s = re.sub(r"(\w+)\.sample\(\s*\w+\s*,\s*([^;]*?),\s*bias\(([^)]*)\)\s*\)(\.[xyzw]+)?;", r"texture(\1, U2G(\2))\4;", s)
    s = re.sub(r"(\w+)\.sample\(\s*\w+\s*,\s*([^;]*?)\)(\.[xyzw]+)?;", r"texture(\1, U2G(\2))\3;", s)
    if "constexpr sampler" in s:
        raise ValueError("an inline sampler the converter couldn't parse")
    if ".sample(" in s:
        raise ValueError("unconverted texture sample")
    s = re.sub(r"\bfma\(", "fma_(", s)
    s = re.sub(r"\brsqrt\(", "inversesqrt(", s)
    s = re.sub(r"\bdfdx\(", "dFdx(", s)
    s = re.sub(r"\bdfdy\(", "dFdy(", s)
    s = s.replace("discard_fragment();", "discard;")
    s = vector_compares(s)
    if stage == "vertex":
        s = re.sub(r"\binput\.(\w+)", r"in_\1", s)
        s = s.replace("output.mtl_Position", "gl_Position")
        s = re.sub(r"\boutput\.(\w+)", r"v_\1", s)
    else:
        s = re.sub(r"\binput\.(\w+)", r"v_\1", s)
        s = s.replace("output.SV_Target0", "gl_FragColor")
        s = re.sub(r"\bmtl_FrontFace\b", "gl_FrontFacing", s)
    s = re.sub(r"^\s*Mtl_\w+ output;\s*$\n?", "", s, flags=re.M)
    s = re.sub(r"^\s*return output;\s*$\n?", "", s, flags=re.M)
    for bad in ("half", "float3", "float4", "input.", "output.", "saturate("):
        if re.search(rf"\b{re.escape(bad)}", s):
            raise ValueError(f"unconverted construct {bad!r}")
    return s


def program_body(src: str) -> str:
    start = src.index("{", src.index("xlatMtlMain("))
    depth, i = 0, start
    while True:
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return src[start + 1:i]
        i += 1


def io_fields(src: str, struct_name: str) -> list[tuple[str, str]]:
    m = re.search(rf"struct {struct_name}\s*\{{(.*?)\}};", src, re.S)
    if not m:
        return []
    out = []
    for line in m.group(1).split(";"):
        mm = re.match(r"\s*(\w+)\s+(\w+)\s*\[\[\s*([^\]]+)\]\]", line)
        if mm:
            out.append((TYPE_MAP.get(mm.group(1), mm.group(1)), mm.group(2)))
    return out


def constant_arrays(src: str) -> list[str]:
    """File-scope `constant float4 ImmCB_0[4] = {...};` -> GLSL const arrays."""
    out = []
    for t, name, n, body in re.findall(r"constant (\w+) (\w+)\[(\d+)\] =\s*\{(.*?)\};", src, re.S):
        gt = TYPE_MAP.get(t, t)
        items = ", ".join(re.sub(r"\bfloat4\b", "vec4", x.strip().rstrip(",")) for x in body.strip().split("\n") if x.strip())
        out.append(f"const {gt} {name}[{n}] = {gt}[{n}]({items});")
    return out


def textures_of(src: str) -> list[str]:
    return re.findall(r"texture2d<[^>]*>\s+(\w+)\s*\[\[", src)


def convert(src: str, stage: str) -> tuple[str, dict[str, tuple[str, int | None]], dict[str, dict[str, str]]]:
    raw = program_body(src)
    samplers = inline_samplers(raw)
    body = convert_body(raw, stage)
    uniforms: dict[str, tuple[str, int | None]] = {}
    decls = []
    for sname, fields in parse_structs(src).items():
        if sname.startswith("Mtl_"):
            continue
        for t, name, n in fields:
            if name.startswith("hlslcc_mtx4x4") or name in PROVIDED:
                continue
            if not re.search(rf"\b{name}\b", body):
                continue
            gt = TYPE_MAP.get(t, t)
            if n and (sname == "AdditionalLights_Type" or name == "_AdditionalShadowParams"):
                n = 1  # per-light arrays: the loop over them runs zero times
            uniforms[name] = (gt, n)
            decls.append(f"uniform {gt} {name}{f'[{n}]' if n else ''};")
    for t in textures_of(src):
        if re.search(rf"\b{t}\b", body):
            uniforms[t] = ("sampler2D", None)
            decls.append(f"uniform sampler2D {t};")
    if stage == "vertex":
        varyings = [f"varying {t} v_{n};" for t, n in io_fields(src, "Mtl_VertexOut") if n != "mtl_Position"]
        glsl = "\n".join([VERTEX_PRELUDE, *decls, *varyings, "void main() {", VERTEX_INPUTS + body.rstrip(), "}", ""])
    else:
        varyings = [f"varying {t} v_{n};" for t, n in io_fields(src, "Mtl_FragmentIn")]
        glsl = "\n".join([FRAGMENT_PRELUDE, *constant_arrays(src), *decls, *varyings, "void main() {", body.rstrip(), "}", ""])
    return glsl, uniforms, samplers


def property_defaults(shader_text: str) -> dict[str, float | list[float] | str]:
    """The shader's Properties block: what Unity uses for a property a material doesn't store.
    Numbers for Float/Range, [r, g, b, a] for Color/Vector, the default texture name for 2D."""
    block = shader_text[shader_text.index("Properties {"):shader_text.index("SubShader {")]
    out: dict[str, float | list[float] | str] = {}
    for m in re.finditer(r"^(?:\[[^\]]*\]\s*)*(\w+)\s*\(\"[^\"]*\",\s*(\w+)(?:\([^)]*\))?\)\s*=\s*(.+?)\s*$", block, re.M):
        name, kind, value = m.groups()
        if kind in ("Float", "Range", "Int"):
            out[name] = float(value)
        elif kind in ("Color", "Vector"):
            out[name] = [float(x) for x in value.strip("()").split(",")]
        elif kind == "2D":
            out[name] = value.split('"')[1]
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("variants")
    ap.add_argument("--shader-text", help="the shader's decompiled ShaderLab text (default: "
                    "<variants>/../MELPOT__Toon__UberToonShader.shader.txt)")
    ap.add_argument("--out", default=str(ROOT / "src" / "engine" / "shaders" / "uberToonGame.ts"))
    args = ap.parse_args()
    vdir = Path(args.variants)
    texts = {}
    for name, fname in SHADER_TEXTS.items():
        path = Path(args.shader_text) if name == "UBER_DEFAULTS" and args.shader_text else vdir.parent / fname
        if not path.exists() and name in ("UBER_DEFAULTS", "EYE_DEFAULTS"):
            # the main characters' shaders: empty defaults would silently zero every property a
            # material doesn't store (_MainColor, _MainLightIntensity, ...)
            raise SystemExit(f"missing ShaderLab text for {name}: {path}")
        texts[name] = path.read_text() if path.exists() else ""

    lines = [
        "// GENERATED by scripts/msl_to_glsl.py from the game's MELPOT/Toon/UberToonShader,",
        "// Character/ToonShader_CharacterEye, MELPOT/Toon/UberToonShader(HLSLMacros) and",
        "// MELPOT/Toon/UberToonShader_Eye (Metal source in the shader bundles).",
        "// Do not edit; regenerate instead.",
        "",
    ]
    all_uniforms: dict[str, tuple[str, int | None]] = {}
    for key, (fname, stage) in PROGRAMS.items():
        glsl, uniforms, samplers = convert((vdir / fname).read_text(), stage)
        for name, decl in uniforms.items():
            # one type table serves every program, so a property must mean the same everywhere
            if all_uniforms.get(name, decl) != decl:
                raise ValueError(f"{key}: {name} is {decl}, elsewhere {all_uniforms[name]}")
        all_uniforms.update(uniforms)
        lines.append(f"export const {key} = {json.dumps(glsl)};")
        lines.append(f"export const {key}_UNIFORMS = {json.dumps(sorted(uniforms))};")
        if samplers:
            lines.append(f"/** Inline sampler states: texture -> filter / mip_filter / address (Metal names). */")
            lines.append(f"export const {key}_SAMPLERS = {json.dumps(samplers, sort_keys=True)} as Record<string, Record<string, string>>;")
        lines.append("")
    types = {k: list(v) for k, v in sorted(all_uniforms.items())}
    lines.append(f"/** Every uniform the programs read: name -> [GLSL type, array length or null]. */")
    lines.append(f"export const UBER_UNIFORMS = {json.dumps(types)} as Record<string, [string, number | null]>;")
    # Each shader keeps its own defaults: they define some of the same properties differently.
    for name, text in texts.items():
        defaults = {k: v for k, v in property_defaults(text).items() if k in all_uniforms} if text else {}
        lines.append("")
        lines.append("/** The shader's property defaults (numbers, [r, g, b, a], or Unity's default texture name). */")
        lines.append(f"export const {name} = {json.dumps(defaults)} as Record<string, number | number[] | string>;")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(PROGRAMS)} programs, {len(all_uniforms)} uniforms)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Convert Project Sekai's character shaders (GLSL ES 3.0 from its Android shader bundle) for three.js.

PJSK's Android bundles keep each shader variant as GLSL ES 3.0 source generated by HLSLcc (one text
per variant with `#ifdef VERTEX` / `#ifdef FRAGMENT` halves), so unlike the Metal → GLSL route of
scripts/msl_to_glsl.py the program bodies run on WebGL2 unchanged. Only their inputs are adapted:
  - uniform blocks become plain uniforms (HLSLcc's own HLSLCC_ENABLE_UNIFORM_BUFFERS switch);
  - vertex inputs come from three's skinning/morph chunks, in the mesh's object space, and
    unity_ObjectToWorld / WorldToObject / MatrixV / MatrixVP are built from three's matrices;
  - _WorldSpaceCameraPos = cameraPosition; SV_Target0 stays the fragment output, the other MRT
    targets (depth-of-field CoC, bloom/rim) are written to locals and dropped.
Every space is three.js world space (the GLB is mirrored from Unity's and the story flips z, but
the programs only take dot products and transforms within one consistent space).

Variants (by the material keywords the exported models use):
  TOON       Hidden/Sekai/Live/Character/Toon-v3, pass Base, _LAMBERT
  EYE        Sekai/Live/Character/Eye-Base, pass Base
  HIGHLIGHT  Sekai/Live/Character/Eye-Highlight, pass Base
Not converted yet: Toon-v3's _UseFaceSDF and _HAIR_SHADOW variants (they read per-frame values the
game computes on the CPU, `_HeadDotDirectionalLightValues`, not traced yet) and the Outline /
Eyelash passes (the outline is drawn from the extra render targets, not by an inflated mesh).

Usage: uv run python -I scripts/pjsk_shader_to_glsl.py data-inspect/pjsk/bundles/shader/live
       [--out src/engine/shaders/pjskToonGame.ts]
"""
from __future__ import annotations

import argparse
import json
import re
import struct
import warnings
from pathlib import Path

import UnityPy
from UnityPy.helpers.CompressionHelper import decompress_lz4

UnityPy.config.FALLBACK_UNITY_VERSION = "2022.3.52f1"
warnings.filterwarnings("ignore", module="UnityPy")

ROOT = Path(__file__).resolve().parent.parent
GLES3 = 9  # ShaderCompilerPlatform.GLES3x
VARIANTS = {
    # output name -> (shader, pass, keywords)
    "TOON": ("Hidden/Sekai/Live/Character/Toon-v3", "Base", {"_LAMBERT"}),
    "EYE": ("Sekai/Live/Character/Eye-Base", "Base", set()),
    "HIGHLIGHT": ("Sekai/Live/Character/Eye-Highlight", "Base", set()),
}
MATRICES = {
    "ObjectToWorld": "modelMatrix",
    "WorldToObject": "inverse(modelMatrix)",
    "MatrixV": "viewMatrix",
    "MatrixVP": "(projectionMatrix * viewMatrix)",
}
VERTEX_INPUTS = """\
#include <beginnormal_vertex>
#include <morphnormal_vertex>
#include <skinbase_vertex>
#include <skinnormal_vertex>
#include <begin_vertex>
#include <morphtarget_vertex>
#include <skinning_vertex>
in_POSITION0 = vec4(transformed, 1.0);
in_NORMAL0 = objectNormal;
in_TEXCOORD0 = uv;
#ifdef USE_UV1
in_TEXCOORD1 = uv1;
#else
in_TEXCOORD1 = vec2(0.0);
#endif
#if defined(USE_COLOR_ALPHA)
in_COLOR0 = color;
#elif defined(USE_COLOR)
in_COLOR0 = vec4(color, 1.0);
#else
in_COLOR0 = vec4(1.0);
#endif
"""


class ShaderBlob:
    """A shader's GLES3 subprograms, by blob index."""

    def __init__(self, tt: dict):
        p = tt["platforms"].index(GLES3)
        blob = bytes(tt["compressedBlob"])
        offs, clens, dlens = tt["offsets"][p], tt["compressedLengths"][p], tt["decompressedLengths"][p]
        self.data = b"".join(decompress_lz4(blob[o:o + c], d) for o, c, d in zip(offs, clens, dlens))
        count = struct.unpack_from("<i", self.data, 0)[0]
        # entry = (offset, length, segment): 12 bytes in Unity 2022
        self.entries = [struct.unpack_from("<ii", self.data, 4 + i * 12) for i in range(count)]

    def text(self, index: int) -> str:
        o, n = self.entries[index]
        chunk = self.data[o:o + n]
        start = chunk.index(b"#ifdef VERTEX")
        end = chunk.find(b"\x00", start)
        return chunk[start:end if end > 0 else len(chunk)].decode("utf-8")


def find_variant(pf: dict, blob: ShaderBlob, pass_name: str, keywords: set[str]) -> str:
    names = pf["m_KeywordNames"]
    for p in pf["m_SubShaders"][0]["m_Passes"]:
        if p["m_State"]["m_Name"] != pass_name:
            continue
        for tier in p["progVertex"]["m_PlayerSubPrograms"]:
            for s in tier:
                if {names[k] for k in s["m_KeywordIndices"]} == keywords:
                    return blob.text(s["m_BlobIndex"])
    raise SystemExit(f"{pf['m_Name']}: no {pass_name} variant {sorted(keywords)}")


def stage(src: str, name: str) -> str:
    """One half (VERTEX / FRAGMENT) of an HLSLcc GLES3 text."""
    start = src.index(f"#ifdef {name}\n") + len(f"#ifdef {name}\n")
    end = src.rindex("#endif", start, src.index("#ifdef FRAGMENT") if name == "VERTEX" else len(src))
    return src[start:end]


def adapt(src: str, kind: str) -> tuple[str, dict[str, list]]:
    s = src.replace("#version 300 es\n", "")
    s = s.replace("#define HLSLCC_ENABLE_UNIFORM_BUFFERS 1", "#define HLSLCC_ENABLE_UNIFORM_BUFFERS 0")
    s = s.replace("#define UNITY_SUPPORTS_UNIFORM_LOCATION 1", "#define UNITY_SUPPORTS_UNIFORM_LOCATION 0")
    s = re.sub(r"^precision .*;\n", "", s, flags=re.M)
    s = re.sub(r"^.*Xhlslcc_Unused.*\n", "", s, flags=re.M)
    used = [m for m in MATRICES if re.search(rf"\bhlslcc_mtx4x4unity_{m}\b", s)]  # MatrixV vs MatrixVP
    for m in used:
        s = re.sub(rf"^\s*(?:uniform|UNITY_UNIFORM)\s+vec4\s+hlslcc_mtx4x4unity_{m}\[4\];\n",
                   f"vec4 hlslcc_mtx4x4unity_{m}[4];\n", s, flags=re.M)
    s = re.sub(r"^uniform\s+vec3 _WorldSpaceCameraPos;\n", "#define _WorldSpaceCameraPos cameraPosition\n", s, flags=re.M)
    prelude = ""
    if kind == "vertex":
        inputs = set(re.findall(r"^in highp vec\d (in_\w+);\n", s, flags=re.M))
        s = re.sub(r"^in highp (vec\d) (in_\w+);\n", r"\1 \2;\n", s, flags=re.M)
        s = "#include <common>\n#include <morphtarget_pars_vertex>\n#include <skinning_pars_vertex>\n" + s
        # only the inputs this program declares
        prelude = "\n".join(line for line in VERTEX_INPUTS.splitlines()
                            if not re.match(r"in_\w+ =", line) or line.split()[0] in inputs) + "\n"
        mats = MATRICES
    else:
        # SV_Target0 stays the program's output; the other MRT targets become locals
        s = re.sub(r"^layout\(location = [1-9]\) out mediump vec4 (SV_Target\d);\n", r"vec4 \1;\n", s, flags=re.M)
        if any(f"hlslcc_mtx4x4unity_{m}" in s for m in ("ObjectToWorld", "WorldToObject")):
            s = "uniform mat4 pjskModelMatrix;\n" + s
        mats = {**MATRICES, "ObjectToWorld": "pjskModelMatrix", "WorldToObject": "inverse(pjskModelMatrix)"}
    if used:
        prelude += "".join(f"{{ mat4 m = {mats[m]}; for (int i = 0; i < 4; i++) hlslcc_mtx4x4unity_{m}[i] = m[i]; }}\n"
                           for m in used)
    s = s.replace("void main()\n{\n", "void main()\n{\n" + prelude, 1)
    uniforms = {}
    for m in re.finditer(r"^\s*(?:uniform|UNITY_UNIFORM|UNITY_LOCATION\(\d+\) uniform)\s+(?:mediump |highp |lowp )?"
                         r"(\w+)\s+(\w+)(?:\[(\d+)\])?;", s, flags=re.M):
        uniforms[m.group(2)] = [m.group(1), int(m.group(3)) if m.group(3) else None]
    return s, uniforms


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bundle", help="the de-obfuscated shader/live bundle (scripts/pjsk_fetch.py)")
    ap.add_argument("--out", default=str(ROOT / "src" / "engine" / "shaders" / "pjskToonGame.ts"))
    a = ap.parse_args()
    env = UnityPy.load(a.bundle)
    shaders = {}
    for o in env.objects:
        if o.type.name == "Shader":
            tt = o.read_typetree()
            shaders[tt["m_ParsedForm"]["m_Name"]] = tt

    lines = [
        "// GENERATED by scripts/pjsk_shader_to_glsl.py from Project Sekai's character shaders",
        "// (GLSL ES 3.0 in the Android shader/live bundle). Do not edit; regenerate instead.",
        "",
    ]
    for key, (shader, pass_name, keywords) in VARIANTS.items():
        tt = shaders[shader]
        text = find_variant(tt["m_ParsedForm"], ShaderBlob(tt), pass_name, keywords)
        vert, vu = adapt(stage(text, "VERTEX"), "vertex")
        frag, fu = adapt(stage(text, "FRAGMENT"), "fragment")
        uniforms = {**vu, **fu}
        lines.append(f"/** {shader}, pass {pass_name}, keywords {sorted(keywords) or 'none'} */")
        lines.append(f"export const {key}_VERT = {json.dumps(vert)};")
        lines.append(f"export const {key}_FRAG = {json.dumps(frag)};")
        lines.append(f"export const {key}_UNIFORMS = {json.dumps(dict(sorted(uniforms.items())))} "
                     "as Record<string, [string, number | null]>;")
        lines.append("")
        print(f"{key}: {shader} {pass_name} {sorted(keywords)}: {len(uniforms)} uniforms")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
